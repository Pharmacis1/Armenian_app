async function precache() {
  console.log('Precaching ' + paragraphs.length + ' paragraphs...');
  for (let i = 0; i < paragraphs.length; i++) {
    const text = paragraphs[i];
    try {
      const res = await fetch('http://localhost:3001/api/reading/tts', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ text })
      });
      const data = await res.json();
      console.log('Paragraph #' + (i + 1) + ': ' + data.url + ' [cached: ' + data.cached + ']');
    } catch (e) {
      console.error('Failed on #' + (i + 1) + ':', e.message);
    }
    await new Promise(r => setTimeout(r, 400));
  }
  console.log('Done precaching paragraphs!');
}

precache();
